/* =========================================================
   APPLY LANGUAGE
   ========================================================= */

function applyLanguage(lang) {

  if (!translations[lang]) {
    lang = "en";
  }

  const dict = translations[lang];

  /* Change HTML language */
  document.documentElement.lang = lang;

  /* Translate normal text */
  document.querySelectorAll("[data-i18n]").forEach(function (element) {

    const key = element.getAttribute("data-i18n");

    if (dict[key] !== undefined) {
      element.textContent = dict[key];
    }

  });


  /* Translate placeholders */
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {

    const key = element.getAttribute("data-i18n-placeholder");

    if (dict[key] !== undefined) {
      element.placeholder = dict[key];
    }

  });


  /* Update selector */
  const selector = document.getElementById("languageSelect");

  if (selector) {
    selector.value = lang;
  }


  /* Save selected language */
  localStorage.setItem("selectedLanguage", lang);

  /* Tell the global system to refresh translations on every page. */
  document.dispatchEvent(new CustomEvent("ejc-language-changed", { detail: { language: lang } }));
}


/* =========================================================
   CHANGE LANGUAGE
   ========================================================= */

function changeLanguage(lang) {

  if (!lang) {

    const selector =
      document.getElementById("languageSelect");

    if (selector) {
      lang = selector.value;
    } else {
      lang = "en";
    }

  }

  applyLanguage(lang);
}


/* Make function available globally */
window.changeLanguage = changeLanguage;


/* =========================================================
   START LANGUAGE SYSTEM
   ========================================================= */

document.addEventListener("DOMContentLoaded", function () {

  const selector =
    document.getElementById("languageSelect");


  /* Load saved language */
  const savedLanguage =
    localStorage.getItem("selectedLanguage") || "en";


  /* Apply saved language */
  applyLanguage(savedLanguage);


  /* Listen for selector changes */
  if (selector) {

    selector.addEventListener("change", function () {

      const selectedLanguage =
        this.value;

      applyLanguage(selectedLanguage);

    });

  }

});
